/**
 * ============================================================================
 *  Ramp — доменная модель "Съезд" (entity) + тип сырого ввода формы
 * ============================================================================
 *
 * Этот файл — слой ДОМЕНА фичи "ramp". Здесь только типы и описание данных,
 * без логики парсинга и без сети. Соответствует таблице `ramp` в БД.
 *
 * Здесь два разных типа — важно их не путать:
 *
 *   1) RampFormInput  — то, что приходит ИЗ ФОРМЫ (сырой ввод).
 *      Всё в виде строк/булевых, как их отдаёт UI. Может быть некорректным.
 *
 *   2) RampEntity     — то, что уходит НА БЭКЕНД (чистая модель).
 *      Уже правильные типы: числа, bool, FK как числовой id, условные поля
 *      могут быть null.
 *
 * Парсер (ramp.parser.ts) — это мост: превращает RampFormInput → RampEntity.
 * ============================================================================
 */

/**
 * RampEntity — что отправляем на бэкенд (зеркало таблицы `ramp`).
 *
 * Поле id здесь НЕ указываем: его присваивает база при создании записи.
 * (Если бы мы редактировали существующую запись — добавили бы id.)
 */
export interface RampEntity {
  /** FK на справочник curb_height (высота бордюра). Числовой id варианта. */
  curb_height: number;

  /** Съезд на проезжую часть есть? (чекбокс) */
  road_access: boolean;

  /** Ограждение у пешеходного перехода есть? (выбор да/нет → bool) */
  walker_barrier: boolean;

  /** Тактильная плитка есть? (чекбокс) */
  tactile_tile: boolean;

  /**
   * Ширина съезда в см (вводится вручную, float).
   * УСЛОВНОЕ ПОЛЕ: имеет смысл только если road_access === true.
   * Если съезда нет — здесь null (по договорённости отправляем null).
   */
  ramp_width: number | null;

  /**
   * Угол наклона в градусах (вводится вручную, float).
   * УСЛОВНОЕ ПОЛЕ: так же зависит от road_access.
   */
  angle_slant: number | null;
}

/**
 * RampFormInput — сырой ввод из формы, ДО парсинга.
 *
 * Числовые поля здесь — строки (string), потому что HTML-инпуты отдают строки.
 * Поле выбора варианта (curb_height) — это выбранный пользователем ТЕКСТ
 * варианта ("2-4cm"), а не id. Превращение текста в id делает парсер
 * через DictionaryService.
 *
 * unknown/string выбраны намеренно: подчёркивают, что данные "грязные"
 * и им нельзя доверять до парсинга.
 */
export interface RampFormInput {
  /** Выбранный текст варианта высоты бордюра, например "2-4cm". */
  curbHeightVariant: string;

  /** Состояние чекбокса "съезд на проезжую часть". */
  roadAccess: boolean;

  /** Состояние выбора "ограждение: да/нет". */
  walkerBarrier: boolean;

  /** Состояние чекбокса "тактильная плитка". */
  tactileTile: boolean;

  /** Ширина съезда, как ввёл пользователь (строка, может быть пустой). */
  rampWidth: string;

  /** Угол наклона, как ввёл пользователь (строка, может быть пустой). */
  angleSlant: string;
}
