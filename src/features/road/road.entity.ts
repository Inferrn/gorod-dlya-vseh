/**
 * ============================================================================
 *  Road — доменная модель "Дорога" (entity) + тип сырого ввода формы
 * ============================================================================
 *
 * Слой ДОМЕНА фичи "road". Соответствует таблице `road` в БД.
 *
 * Особенности этой фичи (чего не было у ramp/crossing):
 *   - traffic_lanes — ЧИСЛО, вводимое вручную (int), а не FK и не чекбокс.
 *     (В исходной таблице стояло bool — это опечатка, подтверждено: это int.)
 *   - ДВА блока условных полей:
 *       * rail_height       — только если есть трамвайные пути;
 *       * audible/countdown  — только если есть светофор.
 * ============================================================================
 */

/**
 * RoadEntity — что отправляем на бэкенд (зеркало таблицы `road`).
 */
export interface RoadEntity {
  /** Количество полос движения (вводится вручную, целое число). */
  traffic_lanes: number;

  /** FK: качество/тип покрытия (8 вариантов). Числовой id варианта. */
  surface_quality: number;

  /** Есть трамвайные пути вдоль дороги? (выбор нет/есть → bool) */
  tram_tracks: boolean;

  /**
   * Высота рельсов над поверхностью дороги, см (float).
   * УСЛОВНОЕ ПОЛЕ: только если tram_tracks === true. Иначе null.
   */
  rail_height: number | null;

  /** Есть светофор? (выбор нет/есть → bool) */
  traffic_light: boolean;

  /**
   * Озвученный светофор? (чекбокс)
   * УСЛОВНОЕ ПОЛЕ: только если traffic_light === true. Иначе null.
   */
  audible_traffic_light: boolean | null;

  /**
   * Светофор с обратным отсчётом? (чекбокс)
   * УСЛОВНОЕ ПОЛЕ: только если traffic_light === true. Иначе null.
   */
  countdown_timer: boolean | null;
}

/**
 * RoadFormInput — сырой ввод из формы, ДО парсинга.
 * traffic_lanes и rail_height — строки (вводятся вручную).
 * surface_quality — выбранный текст варианта. Остальное — чекбоксы.
 */
export interface RoadFormInput {
  /** Количество полос, как ввёл пользователь (строка). */
  trafficLanes: string;

  /** Выбранный текст варианта покрытия, например "асфальт". */
  surfaceQualityVariant: string;

  /** Состояние выбора "трамвайные пути: нет/есть". */
  tramTracks: boolean;

  /** Высота рельсов, как ввёл пользователь (учтётся только если есть пути). */
  railHeight: string;

  /** Состояние выбора "светофор: нет/есть". */
  trafficLight: boolean;

  /** Чекбокс "озвученный" (учтётся только если есть светофор). */
  audibleTrafficLight: boolean;

  /** Чекбокс "обратный отсчёт" (учтётся только если есть светофор). */
  countdownTimer: boolean;
}
