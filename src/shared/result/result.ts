/**
 * ============================================================================
 *  Result<T, E> — тип для безопасной обработки ошибок без исключений
 * ============================================================================
 *
 * ЗАЧЕМ ЭТО НУЖНО:
 * Когда пользователь вводит данные в форму (ширину съезда, угол наклона и т.д.),
 * ввод может быть некорректным: пустая строка, буквы вместо числа, отрицательное
 * значение. Мы НЕ хотим бросать исключения (throw) на каждую ошибку ввода —
 * это усложняет код и легко забыть обработать.
 *
 * Вместо этого парсер возвращает Result: либо "успех со значением" (Ok),
 * либо "ошибка с описанием" (Err). Тот, кто вызывает парсер, обязан явно
 * проверить, что получилось — компилятор TypeScript не даст это пропустить.
 *
 * Это распространённый паттерн (есть в Rust, Kotlin, функциональных языках).
 * ============================================================================
 */

/** Успешный результат: содержит значение типа T. */
export interface Ok<T> {
  readonly ok: true;
  readonly value: T;
}

/** Неуспешный результат: содержит описание ошибки типа E (обычно строка). */
export interface Err<E> {
  readonly ok: false;
  readonly error: E;
}

/**
 * Result — это либо Ok<T>, либо Err<E>.
 * По умолчанию тип ошибки E = string (просто текст ошибки).
 */
export type Result<T, E = string> = Ok<T> | Err<E>;

/** Создать успешный результат. */
export function ok<T>(value: T): Ok<T> {
  return { ok: true, value };
}

/** Создать результат-ошибку. */
export function err<E>(error: E): Err<E> {
  return { ok: false, error };
}

/**
 * Хелпер: собрать множество Result в один.
 * Если ВСЕ результаты успешны — вернёт Ok с массивом значений.
 * Если хотя бы один — ошибка, вернёт ПЕРВУЮ встреченную ошибку.
 *
 * Пригодится в парсере, когда нужно распарсить несколько полей сразу
 * и упасть на первой же ошибке.
 */
export function all<T, E>(results: Result<T, E>[]): Result<T[], E> {
  const values: T[] = [];
  for (const r of results) {
    if (!r.ok) {
      return r; // первая ошибка — сразу возвращаем её
    }
    values.push(r.value);
  }
  return ok(values);
}
