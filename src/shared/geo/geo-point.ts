/**
 * ============================================================================
 *  GeoPoint — координаты объекта на карте
 * ============================================================================
 *
 * ЗАЧЕМ ЭТО НУЖНО:
 * Бэкенд требует latitude/longitude в теле каждого POST (см. Create*Request
 * на сервере). Сами формы про координаты не знают — точку выбирают на карте,
 * поэтому координаты передаются отдельным аргументом в submit() каждой фичи
 * и подмешиваются к телу запроса в репозитории.
 *
 * Имена полей — как ждёт бэкенд (latitude/longitude), чтобы объект можно было
 * класть в тело запроса как есть, без переименований.
 * ============================================================================
 */

export interface GeoPoint {
  /** Широта, градусы: -90..90. */
  latitude: number;

  /** Долгота, градусы: -180..180. */
  longitude: number;
}
