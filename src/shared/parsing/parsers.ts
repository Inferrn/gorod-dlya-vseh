/**
 * ============================================================================
 *  Парс-хелперы — превращают "сырой" ввод формы в строгие типы
 * ============================================================================
 *
 * ЗАЧЕМ ЭТО НУЖНО:
 * Любая HTML-форма отдаёт значения в виде СТРОК (даже число "30" — это строка
 * "30"), а чекбоксы — в виде boolean. Бэкенд же ждёт настоящие числа (int/float)
 * и bool. Эти функции делают аккуратное преобразование с проверками.
 *
 * Каждая функция возвращает Result (см. shared/result), а не бросает исключение:
 * если ввод плохой — вернётся Err с понятным текстом, который можно показать
 * пользователю под полем.
 *
 * Все хелперы здесь — ОБЩИЕ. Их используют парсеры всех фич (ramp, crossing,
 * road...). Если нужен новый тип проверки (например, "число в диапазоне") —
 * добавляй его сюда, чтобы переиспользовать.
 * ============================================================================
 */

import { Result, ok, err } from "../result/result";

/**
 * Распарсить целое число (int).
 * Используется, например, для road.traffic_lanes (количество полос).
 *
 * @param raw   сырое значение из формы (строка, число или undefined)
 * @param field человекочитаемое имя поля — попадёт в текст ошибки
 */
export function parseInt_(raw: unknown, field: string): Result<number> {
  // Приводим к строке и убираем пробелы по краям
  const s = String(raw ?? "").trim();

  if (s === "") {
    return err(`Поле «${field}» не заполнено`);
  }

  // Number() вернёт NaN, если строка не число.
  // Проверяем именно на целое: Number.isInteger отсекает "3.5".
  const n = Number(s);
  if (!Number.isFinite(n) || !Number.isInteger(n)) {
    return err(`Поле «${field}» должно быть целым числом`);
  }
  if (n < 0) {
    return err(`Поле «${field}» не может быть отрицательным`);
  }

  return ok(n);
}

/**
 * Распарсить дробное число (float).
 * Используется для ramp.ramp_width (ширина съезда), ramp.angle_slant (угол),
 * crossing/road.rail_height (высота рельсов) и т.п.
 *
 * Принимает как точку, так и запятую как разделитель ("30,5" → 30.5) —
 * пользователи часто вводят запятую.
 */
export function parseFloat_(raw: unknown, field: string): Result<number> {
  let s = String(raw ?? "").trim();

  if (s === "") {
    return err(`Поле «${field}» не заполнено`);
  }

  // Разрешаем запятую как десятичный разделитель
  s = s.replace(",", ".");

  const n = Number(s);
  if (!Number.isFinite(n)) {
    return err(`Поле «${field}» должно быть числом`);
  }
  if (n < 0) {
    return err(`Поле «${field}» не может быть отрицательным`);
  }

  return ok(n);
}

/**
 * Привести значение чекбокса к boolean.
 * Чекбоксы в HTML отдают true/false, но на всякий случай аккуратно
 * обрабатываем и строковые варианты ("true", "on", "1").
 *
 * Не возвращает ошибку: отсутствующий чекбокс — это просто false.
 */
export function parseBool(raw: unknown): boolean {
  if (typeof raw === "boolean") return raw;
  const s = String(raw ?? "").trim().toLowerCase();
  return s === "true" || s === "on" || s === "1" || s === "да";
}
