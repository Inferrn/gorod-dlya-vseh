/**
 * ============================================================================
 *  MockHttpClient — фейковый HTTP-клиент (бэкенда пока нет)
 * ============================================================================
 *
 * ИДЕЯ:
 * Настоящий HttpClient ходит в сеть. Этот — НЕ ходит, а отдаёт заранее
 * заготовленные данные (mock-справочники). При этом снаружи он выглядит
 * ТОЧНО ТАК ЖЕ, как настоящий: те же методы get()/post(), те же типы ответа.
 *
 * Благодаря этому DictionaryService, парсеры и фичи НЕ ЗНАЮT, что бэка нет —
 * для них это обычный клиент. Когда бэкенд появится, в точке сборки приложения
 * просто заменишь `new MockHttpClient()` на `new HttpClient({ baseUrl })` —
 * и всё заработает по-настоящему. Одна строка.
 *
 * Почему не наследуемся от HttpClient, а делаем отдельный класс:
 * так mock полностью изолирован и не тащит за собой сетевой код. Оба класса
 * просто соблюдают один и тот же "договор" (одинаковые методы) — этого хватает.
 * ============================================================================
 */

import { Result, ok, err } from "../shared/result/result";
import { IHttpClient } from "../shared/http/http-client";
import { MOCK_DICTIONARIES } from "./mock-dictionaries";

/**
 * Небольшая искусственная задержка, чтобы имитировать сеть (мс).
 * Помогает проверить, что интерфейс правильно показывает загрузку.
 * Поставь 0, если задержка мешает.
 */
const FAKE_DELAY_MS = 150;

function delay(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

export class MockHttpClient implements IHttpClient {
  /**
   * GET — отдаёт mock-справочник по эндпоинту.
   * Сигнатура совпадает с настоящим HttpClient.get().
   */
  async get<TResponse>(path: string): Promise<Result<TResponse>> {
    await delay(FAKE_DELAY_MS);

    // Ищем справочник по пути. Нормализуем ведущий слэш на всякий случай.
    const key = path.startsWith("/") ? path : "/" + path;
    const data = MOCK_DICTIONARIES[key];

    if (data === undefined) {
      // Такого справочника в mock нет — ведём себя как сервер с 404.
      return err(`[mock] Неизвестный эндпоинт справочника: ${key}`);
    }

    // as unknown as TResponse — mock знает, что для справочников это DictionaryItem[],
    // а вызывающий код ожидает свой тип. Приведение безопасно в рамках заглушки.
    return ok(data as unknown as TResponse);
  }

  /**
   * POST — в mock-режиме реальной отправки нет.
   * Возвращаем ошибку с понятным текстом, чтобы было видно: отправитель
   * ещё не подключён к настоящему бэку (это соответствует текущему заданию).
   *
   * Когда захотим сымитировать успешную отправку — можно вернуть здесь
   * ok({ id: случайное_число }). Пока намеренно не делаем.
   */
  async post<TResponse>(path: string, _body: unknown): Promise<Result<TResponse>> {
    await delay(FAKE_DELAY_MS);
    return err(
      `[mock] Отправка на ${path} не выполнена: бэкенд ещё не подключён. ` +
        `Это ожидаемо на текущем этапе.`,
    );
  }
}
