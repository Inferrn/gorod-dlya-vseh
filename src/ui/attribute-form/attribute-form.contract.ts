/**
 * ============================================================================
 *  AttributeForm — общий "договор" для всех форм (ramp / crossing / road)
 * ============================================================================
 *
 * ЗАЧЕМ:
 * Каркас-переключатель (attribute-form.ts) не должен знать, какая именно форма
 * внутри. Ему достаточно, что у любой формы есть две способности:
 *   - render()  — построить себя (асинхронно, т.к. грузит справочники);
 *   - collect() — отдать собранный сырой ввод.
 *
 * Благодаря этому переключатель работает со всеми тремя формами ОДИНАКОВО,
 * а не через три отдельные ветки кода. Добавишь четвёртый тип — просто сделаешь
 * ещё одну форму по этому договору, каркас трогать не придётся.
 *
 * Тип собранных данных у каждой формы свой (RampFormInput / CrossingFormInput /
 * RoadFormInput), поэтому договор обобщён параметром TInput.
 * ============================================================================
 */

import { Result } from "../../shared/result/result";

export interface AttributeForm<TInput> {
  /** Построить форму (грузит справочники, рисует поля). */
  render(): Promise<Result<void>>;
  /** Собрать текущий сырой ввод формы. */
  collect(): TInput;
}
